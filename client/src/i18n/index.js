const STORAGE_KEY = "language";
const DEFAULT_LANGUAGE = "th";
const SUPPORTED_LANGUAGES = ["th", "en"];

export function getInitialLanguage() {
  const savedLanguage = localStorage.getItem(STORAGE_KEY);
  return SUPPORTED_LANGUAGES.includes(savedLanguage) ? savedLanguage : DEFAULT_LANGUAGE;
}

export function persistLanguage(language) {
  if (SUPPORTED_LANGUAGES.includes(language)) {
    localStorage.setItem(STORAGE_KEY, language);
  }
}

export function createTranslator(language) {
  const dictionary = translations[language] || translations[DEFAULT_LANGUAGE];

  return (key, params = {}) => {
    const value = key.split(".").reduce((current, part) => current?.[part], dictionary);
    const fallback = key.split(".").reduce(
      (current, part) => current?.[part],
      translations[DEFAULT_LANGUAGE],
    );
    const template = typeof value === "string" ? value : typeof fallback === "string" ? fallback : key;

    return Object.entries(params).reduce(
      (text, [paramKey, paramValue]) => text.replaceAll(`{${paramKey}}`, paramValue),
      template,
    );
  };
}

export function getPageMeta(pageId, language) {
  const page = translations[language]?.pages?.[pageId] || translations.th.pages[pageId];
  return page || translations[language]?.pages?.dashboard || translations.th.pages.dashboard;
}

